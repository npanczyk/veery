    from veery.viz import plot_tree_diagram

    # saved next to this file (results/ is gitignored) so the figures can be inspected
    results_path = Path(__file__).parent / "results"
    results_path.mkdir(exist_ok=True)

    fig, ax = plot_tree_diagram(
        demo_tree["root"], save_path=results_path / "demo_tree.png"
    )
